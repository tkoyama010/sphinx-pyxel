"""Sphinx-pyxel banner: the Sphinx-logo silhouette drawn with Pyxel.

The Sphinx-docs logo (https://sphinx-immaterial.readthedocs.io/en/latest/_images/sphinx_logo.svg)
is a black sphinx silhouette. This module redraws it as Pyxel pixel art --
each pixel of a 100x75 trace of that SVG becomes one Pyxel pixel -- and lays
the project title beside it in the Pyxel pixel font (PixelMplus12) with a
grey outline, echoing the Pyxel logo wordmark.

Run interactively::

    pyxel docs/banner.py

Render the static ``banner.png`` (headless, no window)::

    python docs/banner.py --save docs/_static/banner.png --scale 4

``draw_banner(g)`` is shared by the live app and the PNG export, so the
committed banner is always byte-identical to what the app shows.
"""

