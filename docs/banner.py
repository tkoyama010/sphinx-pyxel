def draw_banner(g, font=None) -> None:
    """Draw the banner onto ``g`` (the Pyxel screen or an image bank).

    ``font`` is a ``pyxel.Font``; when ``None`` the standard Pyxel font is
    used (live app passes a PixelMplus font, the headless export does too).
    """
    g.cls(BG)

    # The Sphinx silhouette, blitted directly onto the background.
    g.set(LOGO_X, LOGO_Y, LOGO_DATA)

    _draw_text(g, TITLE, TITLE_X, TITLE_Y, BLACK, None, font)


def _draw_text(g, s, x, y, col, bcol, font=None) -> None:
    """Draw ``s`` with an optional 1px ``bcol`` outline + ``col`` fill."""
    if bcol is not None:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if dx or dy:
                    g.text(x + dx, y + dy, s, bcol, font)
    g.text(x, y, s, col, font)


def update() -> None:
    pass


def draw() -> None:
    draw_banner(pyxel, _font)


_font = None


def main() -> None:
    global _font
    args = sys.argv[1:]
    save = scale = None
    if "--save" in args:
        save = args[args.index("--save") + 1]
    if "--scale" in args:
        scale = int(args[args.index("--scale") + 1])

    if save:
        save = os.path.abspath(save)

    pyxel.init(W, H)

    # Match the banner background (palette 7) to pure white so it blends
    # into GitHub's README body color.
    pyxel.colors[7] = 0xFFFFFF

    _font = pyxel.Font(FONT_PATH, FONT_SIZE)

    if save:
        img = pyxel.Image(W, H)
        draw_banner(img, _font)
        img.save(save, scale or 1)
        print(f"saved {save}")
        return

    pyxel.run(update, draw)


if __name__ == "__main__":
    main()
